"""MCP server exposing Gemma 2 2B's internals via Gemma Scope SAEs."""

import threading
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from typing import Any

from mcp.server.mcpserver import MCPServer

from interp_playground.backend import Backend

DEFAULT_LAYER = 12

backend = Backend()


@asynccontextmanager
async def lifespan(_: MCPServer) -> AsyncIterator[None]:
    # Loading takes ~20s. Do it in the background so the client can connect;
    # the first tool call waits on the backend's lock until it's done.
    threading.Thread(target=backend.warm_up, args=([DEFAULT_LAYER],), daemon=True).start()
    yield


server = MCPServer(
    name="interp-playground",
    instructions=(
        "Tools for inspecting Gemma 2 2B's internals with Gemma Scope sparse-autoencoder "
        "(SAE) features on the residual stream. Features are numbered 0-16383 per layer; "
        "layers are 0-25. Feature labels are auto-generated by a small LLM from top "
        "activations: treat them as hypotheses, and check them against where the feature "
        "actually fires."
    ),
    lifespan=lifespan,
    log_level="WARNING",
)


@server.tool()
def run_prompt(
    prompt: str,
    layers: list[int] | None = None,
    top_k: int = 5,
    features: list[int] | None = None,
    max_new_tokens: int = 0,
    include_hidden: bool = False,
) -> dict[str, Any]:
    """Run a prompt through the model and report which SAE features are active.

    Returns, per layer:
    - tokens: the text's tokens (<bos> omitted). Positions elsewhere are
      0-based indexes into this list.
    - top_features: the 10 features most strongly active anywhere in the text,
      each at its peak position, with its Neuronpedia label, density
      (fraction of all tokens it fires on) and the output tokens it promotes.
    - per_token: for each position, its top_k features (omitted if top_k=0).
    - watched: for each feature in `features`, its activation at every
      position. Use this to test a hypothesis about specific features; it's
      exact (0 means not firing) and far more compact than a large top_k.
    - hidden: how many features were hidden from rankings, by reason.

    `act` is the raw activation. `rel` is act / the feature's typical max
    activation, so rel near 1 means firing about as hard as it ever does.
    Rankings use rel. Two kinds of features are hidden from rankings by
    default (watched features are always reported):
    - dense: active on >10% of all tokens, so they carry little meaning.
    - position_artifact: fire on whatever token comes first, regardless of
      content (detected with probe prompts when a layer loads).

    Args:
        prompt: Text to run. Gemma 2 2B is a base model, not a chat model.
        layers: Residual-stream layers to read (0-25). Default [12].
        top_k: Features to list per position (0-20).
        features: Feature ids (0-16383) to report at every position.
        max_new_tokens: If > 0, greedily generate this many tokens first and
            analyze prompt + completion.
        include_hidden: Include dense and position-artifact features in rankings.
    """
    return backend.run_prompt(
        prompt,
        layers or [DEFAULT_LAYER],
        top_k=max(0, min(top_k, 20)),
        features=features or [],
        max_new_tokens=max(0, min(max_new_tokens, 200)),
        include_hidden=include_hidden,
    )


@server.tool()
def steer(
    prompt: str,
    feature: int,
    layer: int = DEFAULT_LAYER,
    scales: list[float] | None = None,
    max_new_tokens: int = 30,
    control: bool = True,
    seed: int = 0,
) -> dict[str, Any]:
    """Add an SAE feature's direction to the residual stream and compare outputs.

    At each scale, adds scale x the feature's (unit-norm) decoder direction at
    `layer`, at every position, during greedy generation. Scale is in the
    feature's activation units: scale = max_act matches the feature's own
    strongest natural firing. Negative scales push away from the feature.

    With control=true (default), each scale is also run with a random unit
    direction of the same size. Compare the two: an effect is attributable to
    the feature only if the steered run shows it and the control doesn't.
    Repetitive text ("I love the beach. I love the beach.") appears with random
    pushes too, so it isn't evidence by itself.

    Returns the baseline and, per scale, `steered` and `control` runs, each with:
    - completion: the generated text.
    - p_promoted: next-token probability, at the end of the prompt, on the
      feature's top 10 promoted tokens (listed in promoted_tokens).
    - kl: KL(baseline || run) at that position; how disrupted the model is.
    - promoted_in_completion: count of generated tokens that are promoted tokens.
    frac_of_resid is |scale| / the typical residual norm at that layer.

    Args:
        prompt: Text to continue. Gemma 2 2B is a base model, not a chat model.
        feature: Feature id (0-16383).
        layer: Residual-stream layer of the feature's SAE (0-25). Default 12.
        scales: Up to 6 scales. Default: 1x, 2x, 4x the feature's max_act.
        max_new_tokens: Tokens to generate per run (1-100).
        control: Also run a random direction at each scale.
        seed: Seed for the random control direction.
    """
    if scales is not None:
        if not 1 <= len(scales) <= 6:
            raise ValueError("pass 1-6 scales")
        if any(abs(x) > 2000 for x in scales):
            raise ValueError("scales must be within +/-2000")
    return backend.steer(
        prompt,
        feature,
        layer,
        scales,
        max_new_tokens=max(1, min(max_new_tokens, 100)),
        control=control,
        seed=seed,
    )


@server.tool()
def feature_info(feature: int, layer: int = DEFAULT_LAYER) -> dict[str, Any]:
    """Everything known about one SAE feature.

    Returns its Neuronpedia label, density (fraction of all tokens it fires
    on), max activation, whether it's hidden from run_prompt rankings and why,
    the output tokens its direction promotes and suppresses most (from the
    unembedding), the 5 features with the most similar decoder directions,
    Neuronpedia's top activating examples (peak token in [[brackets]]; null if
    Neuronpedia is unreachable), and its Neuronpedia URL.

    The label is auto-generated from the top examples, so it describes the
    feature's strongest activations; check promotes/similar_features and the
    examples against each other before trusting it.

    Args:
        feature: Feature id (0-16383).
        layer: Residual-stream layer of the feature's SAE (0-25). Default 12.
    """
    return backend.feature_info(feature, layer)


@server.tool()
def logit_lens(prompt: str, position: int = -1, top_k: int = 5) -> dict[str, Any]:
    """What the model would predict next if it stopped at each layer.

    Applies the final norm and unembedding to the residual stream after every
    layer, at one position. Returns per layer the top_k tokens with
    probabilities and `p_final`, that layer's probability for the token the
    last layer actually predicts. A rising p_final shows when the answer
    forms. Early and middle layers often show junk tokens (the residual stream
    isn't in the output basis yet); read p_final, not the junk.

    Args:
        prompt: Text to analyze. Gemma 2 2B is a base model, not a chat model.
        position: 0-based index into the returned tokens; negative counts
            from the end. Default -1, the last token (the next-token prediction).
        top_k: Tokens to list per layer (1-10).
    """
    return backend.logit_lens(prompt, position, top_k=max(1, min(top_k, 10)))


@server.tool()
def ablate(
    prompt: str,
    feature: int,
    layer: int = DEFAULT_LAYER,
    value: float | None = None,
    max_new_tokens: int = 0,
    top_k: int = 5,
) -> dict[str, Any]:
    """Remove a feature's contribution to the residual stream and measure the effect.

    At every position, subtracts (act - target) x the feature's decoder
    direction, where target is 0 (default) or `value` (clamp). Unlike steer,
    this only changes positions where the feature is active, by exactly its
    own contribution, so a null result means the model doesn't rely on this
    feature here. Compare with steer at a negative scale, which pushes at every
    position regardless.

    Returns active_positions (where the feature fired, its activation, and how
    much ablating it changes log p of the actual next token there),
    next_token (top_k predictions after the prompt, baseline vs ablated, with
    KL), and optionally completions.

    Args:
        prompt: Text to run. Gemma 2 2B is a base model, not a chat model.
        feature: Feature id (0-16383).
        layer: Residual-stream layer of the feature's SAE (0-25). Default 12.
        value: Clamp the feature to this activation instead of zeroing it.
        max_new_tokens: If > 0, also generate completions (0-100).
        top_k: Next-token predictions to list (1-10).
    """
    return backend.ablate(
        prompt,
        feature,
        layer,
        value,
        max_new_tokens=max(0, min(max_new_tokens, 100)),
        top_k=max(1, min(top_k, 10)),
    )


def main() -> None:
    server.run("stdio")


if __name__ == "__main__":
    main()
